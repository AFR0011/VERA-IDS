"""
5.ProtocolB_GridRunner.py
=========================

Purpose
-------
Run a scenario-driven Protocol B grid search on *valid* LOAO/open-set scenarios only.

This script is the bridge between:
    1) the support-audit stage, and
    2) actual model training / threshold / tau selection.

Design choices
--------------
This is not a blind Cartesian product over everything. The structure is:

    valid scenario manifest
        -> model family / model params / weighting choice
            -> internal validation search for threshold and tau
                -> test evaluation

That matters because your current bottleneck is scenario validity, not a shortage of
sweep knobs.

What this script does
---------------------
For each manifest generated by 4.ProtocolB_SupportAudit.py, it can:
    - fit a preprocessor using your existing V4.1 helper script
    - train Stage 1 as XGBoost or RandomForest
    - train Stage 2 as XGBoost or RandomForest
    - optionally remove holdout-family rows from Stage 1 training (strict LOAO)
    - tune the Stage 1 threshold on validation under family-aware criteria
    - tune tau on validation under open-set constraints
    - evaluate the system on test
    - write one run folder per scenario / model combo
    - append results to an aggregate CSV

Important scope note
--------------------
This script does NOT replace your entire V4.1A/V4.1B pipeline. It intentionally focuses
on the thesis work you asked for now:
    - valid LOAO reruns
    - support rules
    - RF vs XGB comparison
    - class weighting / family weighting
    - threshold / tau selection logic

It reuses the preprocessor logic from your existing V4.1 helper script so feature
handling stays aligned with your current workflow.
"""

