def stable_short_hash(obj: Dict[str, object], n: int = 10) -> str:
    s = json.dumps(obj, sort_keys=True, separators=(",", ":"))
    return hashlib.sha1(s.encode("utf-8")).hexdigest()[:n]

def canonical_col(name: str) -> str:
    return str(name).strip().lower().replace(" ", "_")


def load_json(path: str) -> Dict[str, object]:
    """
    Load a JSON object with better diagnostics.

    Why this exists:
    - The audit folder may contain stale or malformed JSON files from earlier runs.
    - A broad manifest glob can accidentally catch non-manifest JSON files.
    - Some malformed files are still recoverable if they contain one valid JSON object
      followed by extra garbage or a duplicated second object.

    Behavior:
    - First try normal json.loads.
    - If that fails with "Extra data", try raw_decode and keep the first object only
      if it looks like a scenario manifest. This is a pragmatic recovery path, not a
      license to keep bad files around forever.
    """
    with open(path, "r", encoding="utf-8") as f:
        raw = f.read()

    try:
        obj = json.loads(raw)
    except JSONDecodeError as e:
        stripped = raw.lstrip()
        if e.msg == "Extra data":
            try:
                decoder = json.JSONDecoder()
                obj, end = decoder.raw_decode(stripped)
                if not isinstance(obj, dict):
                    raise RuntimeError(f"Manifest is not a JSON object: {path}")
                required = {"dataset", "processed_dir", "holdout_family", "valid_known_families"}
                if not required.issubset(set(obj.keys())):
                    raise RuntimeError(f"Recovered first JSON object is not a scenario manifest: {path}")
                trailing = stripped[end:].strip()
                if trailing:
                    progress_print(f"[WARN] Recovered manifest by using first JSON object only: {path}")
                return obj
            except Exception as inner:
                raise RuntimeError(f"Malformed JSON manifest: {path} :: {e}") from inner
        raise RuntimeError(f"Malformed JSON manifest: {path} :: {e}") from e

    if not isinstance(obj, dict):
        raise RuntimeError(f"Manifest root must be a JSON object: {path}")
    return obj


def write_json(path: str, obj: Dict[str, object]) -> None:
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2)


def list_parts(dataset_dir: str, split: str) -> List[str]:
    out = []
    out.extend(sorted(glob.glob(os.path.join(dataset_dir, split, "*.parquet"))))
    out.extend(sorted(glob.glob(os.path.join(dataset_dir, split, "*.csv"))))
    out.extend(sorted(glob.glob(os.path.join(dataset_dir, split, "*.csv.gz"))))
    out.extend(sorted(glob.glob(os.path.join(dataset_dir, f"{split}_*.parquet"))))
    out.extend(sorted(glob.glob(os.path.join(dataset_dir, f"{split}_*.csv"))))
    out.extend(sorted(glob.glob(os.path.join(dataset_dir, f"{split}_*.csv.gz"))))
    # Deduplicate
    seen = set()
    final = []
    for p in out:
        if p not in seen:
            final.append(p)
            seen.add(p)
    return final


def read_part(path: str, usecols: Optional[List[str]] = None) -> pd.DataFrame:
    if path.lower().endswith(".parquet"):
        return pd.read_parquet(path, columns=usecols)
    if path.lower().endswith(".csv") or path.lower().endswith(".csv.gz"):
        return pd.read_csv(path, usecols=usecols)
    raise RuntimeError(f"Unsupported part type: {path}")


def collect_split_frame(dataset_dir: str, split: str, usecols: List[str], max_rows: Optional[int], seed: int) -> pd.DataFrame:
    """
    Collect a split into one DataFrame.

    If max_rows is None, the full split is read.
    If max_rows is an integer, the function keeps an approximate bounded sample by repeatedly
    mixing the current buffer with each new chunk and downsampling back to max_rows.

    This is not a perfect reservoir implementation, but it is simple, repeatable, and good
    enough for large-scale validation sweeps.
    """
    rng = np.random.RandomState(seed)
    frames: List[pd.DataFrame] = []
    current: Optional[pd.DataFrame] = None

    for part in list_parts(dataset_dir, split):
        df = read_part(part, usecols=usecols)
        df.columns = [canonical_col(c) for c in df.columns]

        if max_rows is None:
            frames.append(df)
            continue

        if current is None:
            if len(df) <= max_rows:
                current = df.copy()
            else:
                current = df.sample(n=max_rows, random_state=rng.randint(0, 2**31 - 1)).reset_index(drop=True)
            continue

        mixed = pd.concat([current, df], axis=0, ignore_index=True)
        if len(mixed) > max_rows:
            current = mixed.sample(n=max_rows, random_state=rng.randint(0, 2**31 - 1)).reset_index(drop=True)
        else:
            current = mixed.reset_index(drop=True)

    if max_rows is None:
        if not frames:
            return pd.DataFrame(columns=usecols)
        out = pd.concat(frames, axis=0, ignore_index=True)
        out.columns = [canonical_col(c) for c in out.columns]
        return out

    if current is None:
        return pd.DataFrame(columns=[canonical_col(c) for c in usecols])
    current.columns = [canonical_col(c) for c in current.columns]
    return current


