def discover_manifests() -> List[str]:
    """
    Discover valid scenario manifests.

    Preferred source: eligible_holdouts_all.csv (or per-dataset eligible_holdouts.csv), because
    that is less fragile than blindly loading every JSON file found under manifests/.

    Fallback source: manifest_glob, but filtered to the expected filename pattern
    <dataset>__holdout_<family>.json so random JSON files do not get mistaken for manifests.
    """
    audit_roots = [str(x) for x in list(CFG.get("audit_roots") or []) if str(x).strip()]
    if not audit_roots:
        audit_roots = [str(CFG["audit_root"])]
    candidates: List[str] = []
    audit_index_seen = False

    for audit_root in audit_roots:
        global_csv = os.path.join(audit_root, "eligible_holdouts_all.csv")
        if os.path.exists(global_csv):
            audit_index_seen = True
            try:
                df = pd.read_csv(global_csv)
                if "manifest_path" in df.columns:
                    candidates.extend([str(x) for x in df["manifest_path"].dropna().astype(str).tolist() if str(x).strip()])
            except Exception as exc:
                progress_print(f"[WARN] Could not read {global_csv}: {exc}")

        for csv_path in sorted(glob.glob(os.path.join(audit_root, "*", "eligible_holdouts.csv"))):
            audit_index_seen = True
            try:
                df = pd.read_csv(csv_path)
                if "manifest_path" in df.columns:
                    candidates.extend([str(x) for x in df["manifest_path"].dropna().astype(str).tolist() if str(x).strip()])
            except Exception as exc:
                progress_print(f"[WARN] Could not read {csv_path}: {exc}")

    if not candidates:
        manifest_globs = CFG["manifest_glob"]
        if isinstance(manifest_globs, (list, tuple)):
            glob_patterns = [str(x) for x in manifest_globs]
        else:
            glob_patterns = [str(manifest_globs)]
        for pattern in glob_patterns:
            for path in sorted(glob.glob(pattern)):
                base = os.path.basename(path)
                if "__holdout_" in base and base.lower().endswith(".json"):
                    candidates.append(path)

    normed: List[str] = []
    seen = set()
    for p in candidates:
        p_norm = os.path.normpath(str(p))
        if p_norm in seen:
            continue
        if not os.path.isfile(p_norm):
            continue
        seen.add(p_norm)
        normed.append(p_norm)

    if not normed:
        if audit_index_seen:
            return []
        raise RuntimeError(
            "No manifests found. Run 4.ProtocolB_SupportAudit.py first or update CFG['audit_root']/CFG['manifest_glob']."
        )
    return sorted(normed)


def build_run_plan(manifest_paths: List[str]) -> List[Dict[str, object]]:
    """
    Build the outer grid of training runs.

    We purposely keep threshold and tau search *inside* each run rather than creating a new
    run for every threshold/tau value.
    """
    rows: List[Dict[str, object]] = []

    profiles = dict(CFG.get("model_profiles") or {})

    for manifest_path in manifest_paths:
        try:
            manifest = load_json(manifest_path)
        except Exception as exc:
            raise RuntimeError(f"Failed to load scenario manifest: {manifest_path} :: {exc}") from exc
        allowed_loao_stage1 = list(manifest.get("apply_loao_stage1_values", [])) or [False]
        allowed_loao_stage1 = [x for x in CFG["apply_loao_stage1_values"] if x in allowed_loao_stage1]

        if profiles:
            for profile_name, profile in profiles.items():
                model_family = str(profile["model_family"])
                allowed_datasets_for_profile = {str(x) for x in list(profile.get("datasets", []) or [])}
                if allowed_datasets_for_profile and str(manifest["dataset"]) not in allowed_datasets_for_profile:
                    continue
                s1_weight_modes = list(profile.get("stage1_weight_modes", ["none"]))
                s2_weight_modes = list(profile.get("stage2_weight_modes", ["none"]))
                s1_grid = list(profile.get("stage1_param_grid", [profile.get("stage1_params", {})]))
                s2_grid = list(profile.get("stage2_param_grid", [profile.get("stage2_params", {})]))
                for apply_loao_stage1, weight_mode, stage2_weight_mode, s1_params, s2_params in itertools.product(
                    allowed_loao_stage1,
                    s1_weight_modes,
                    s2_weight_modes,
                    s1_grid,
                    s2_grid,
                ):
                    rows.append(
                        {
                            "manifest_path": manifest_path,
                            "dataset": manifest["dataset"],
                            "holdout_family": manifest["holdout_family"],
                            "model_family": model_family,
                            "model_profile": str(profile_name),
                            "apply_loao_stage1": bool(apply_loao_stage1),
                            "stage1_weight_mode": str(weight_mode),
                            "stage2_weight_mode": str(stage2_weight_mode),
                            "stage1_params": dict(s1_params),
                            "stage2_params": dict(s2_params),
                        }
                    )
            continue

        for model_family in CFG["model_families"]:
            model_weight_modes = list((CFG.get("stage1_weight_modes_by_model") or {}).get(model_family, CFG["stage1_weight_modes"]))
            for apply_loao_stage1, weight_mode, stage2_weight_mode, s1_params, s2_params in itertools.product(
                allowed_loao_stage1,
                model_weight_modes,
                CFG.get("stage2_weight_modes", ["balanced"]),
                CFG["stage1_param_grid"][model_family],
                CFG["stage2_param_grid"][model_family],
            ):
                rows.append(
                    {
                        "manifest_path": manifest_path,
                        "dataset": manifest["dataset"],
                        "holdout_family": manifest["holdout_family"],
                        "model_family": model_family,
                        "model_profile": model_family,
                        "apply_loao_stage1": bool(apply_loao_stage1),
                        "stage1_weight_mode": str(weight_mode),
                        "stage2_weight_mode": str(stage2_weight_mode),
                        "stage1_params": dict(s1_params),
                        "stage2_params": dict(s2_params),
                    }
                )
    return rows


def sanitize_for_path_token(value: object) -> str:
    s = str(value).strip()
    s = re.sub(r'[\\/:*?"<>|]+', "_", s)
    s = re.sub(r"\s+", "_", s)
    s = re.sub(r"_+", "_", s).strip("._")
    return s or "NA"


def combo_run_name(row: Dict[str, object]) -> str:
    s1 = row["stage1_params"]
    s2 = row["stage2_params"]
    safe_holdout = sanitize_for_path_token(row["holdout_family"])
    safe_profile = sanitize_for_path_token(row.get("model_profile", row["model_family"]))
    return (
        f"{row['dataset']}__holdout_{safe_holdout}"
        f"__{safe_profile}"
        f"__loaoS1_{int(bool(row['apply_loao_stage1']))}"
        f"__w1_{row['stage1_weight_mode']}"
        f"__w2_{row.get('stage2_weight_mode', 'balanced')}"
        f"__s1_{stable_short_hash(s1)}"
        f"__s2_{stable_short_hash(s2)}"
    )


def main() -> None:
    safe_mkdir(str(CFG["runs_root"]))
    helper = load_helper_module(str(CFG["base_helper_script"]))

    manifest_paths = discover_manifests()
    if CFG.get("max_manifests") is not None:
        manifest_paths = manifest_paths[: int(CFG["max_manifests"])]
    plan = build_run_plan(manifest_paths)
    plan_columns = [
        "manifest_path",
        "dataset",
        "holdout_family",
        "model_profile",
        "model_family",
        "apply_loao_stage1",
        "stage1_weight_mode",
        "stage2_weight_mode",
        "stage1_params",
        "stage2_params",
        "run_name",
    ]
    plan_df = pd.DataFrame(
        [
            {
                **{k: v for k, v in row.items() if k not in {"stage1_params", "stage2_params"}},
                "stage1_params": json.dumps(row["stage1_params"], sort_keys=True),
                "stage2_params": json.dumps(row["stage2_params"], sort_keys=True),
                "run_name": combo_run_name(row),
            }
            for row in plan
        ],
        columns=plan_columns,
    )
    plan_path = os.path.join(str(CFG["runs_root"]), "scenario_plan.csv")
    plan_df.to_csv(plan_path, index=False)
    progress_print(f"Wrote plan: {plan_path}")
    progress_print(f"Planned runs: {len(plan_df)}")

    if plan_df.empty:
        progress_print("No valid manifests were available for this audit root. Stopping before training.")
        return

    if bool(CFG["dry_run"]):
        progress_print("dry_run=True -> stopping after plan creation.")
        return

    results_rows: List[Dict[str, object]] = []
    aggregate_path = os.path.join(str(CFG["runs_root"]), "aggregate_results.csv")

    # Allow resume by loading any existing aggregate CSV first.
    if os.path.exists(aggregate_path):
        try:
            results_rows = pd.read_csv(aggregate_path).to_dict("records")
        except Exception:
            results_rows = []

    for idx, row in enumerate(plan, start=1):
        run_name = combo_run_name(row)
        run_dir = os.path.join(str(CFG["runs_root"]), run_name)

        summary_path = os.path.join(run_dir, "summary.json")
        error_path = os.path.join(run_dir, "error.json")

        # Skip only successfully completed runs
        if os.path.isfile(summary_path):
            progress_print(f"[{idx}/{len(plan)}] skip completed -> {run_name}")
            continue

        # Optional: also skip failed runs
        # if os.path.isfile(error_path):
        #     print(f"[{idx}/{len(plan)}] skip failed -> {run_name}")
        #     continue

        progress_print(f"[{idx}/{len(plan)}] running -> {run_name}")
        safe_mkdir(run_dir)

        try:
            manifest = load_json(str(row["manifest_path"]))
            combo = {
                "model_family": row["model_family"],
                "model_profile": row.get("model_profile", row["model_family"]),
                "apply_loao_stage1": row["apply_loao_stage1"],
                "stage1_weight_mode": row["stage1_weight_mode"],
                "stage2_weight_mode": row.get("stage2_weight_mode", "balanced"),
                "stage1_params": row["stage1_params"],
                "stage2_params": row["stage2_params"],
            }
            summary = run_one_combo(helper, manifest, run_dir, combo)
            summary["run_name"] = run_name
            summary["run_dir"] = run_dir
            results_rows.append(summary)
            pd.DataFrame(results_rows).to_csv(aggregate_path, index=False)

        except Exception as exc:
            err = {
                "run_name": run_name,
                "run_dir": run_dir,
                "error": str(exc),
                "traceback": traceback.format_exc(),
            }
            write_json(os.path.join(run_dir, "error.json"), err)
            progress_print(f"  ERROR in {run_name}: {exc}")

    if results_rows:
        pd.DataFrame(results_rows).to_csv(aggregate_path, index=False)
        progress_print(f"\nFinished. Aggregate results: {aggregate_path}")
    else:
        progress_print("\nFinished, but no successful runs were recorded.")


if __name__ == "__main__":
    main()
