def run_one_combo(helper, manifest: Dict[str, object], run_dir: str, combo: Dict[str, object]) -> Dict[str, object]:
    """
    Train one scenario/model combo and return a flat result row.

    combo keys:
        - model_family
        - apply_loao_stage1
        - stage1_weight_mode
        - stage1_params
        - stage2_params
    """
    safe_mkdir(run_dir)
    write_json(os.path.join(run_dir, "scenario_manifest.json"), manifest)
    write_json(os.path.join(run_dir, "combo.json"), combo)

    dataset = str(manifest["dataset"])
    dataset_dir = str(manifest["processed_dir"])
    y1_col = canonical_col(str(manifest["y_stage1_col"]))
    y2_col = canonical_col(str(manifest["y_stage2_col"]))
    benign_label = str(manifest["benign_label"])
    unknown_label = str(manifest.get("unknown_label", "Unknown"))
    holdout_family = str(manifest["holdout_family"])
    manifest_known_families = list(manifest["valid_known_families"])
    valid_known_families = list(manifest_known_families)
    optimize_tau_for_unknown = bool(manifest.get("optimize_tau_for_unknown", True))

    max_train_rows = dict(CFG["max_train_rows"]).get(dataset, None)
    max_val_rows = dict(CFG["max_val_rows"]).get(dataset, None)
    max_test_rows = dict(CFG["max_test_rows"]).get(dataset, None)
    seed = int(CFG["random_seed"])

    # -------------------------------------------------------------------------
    # 1) Preprocessor
    # -------------------------------------------------------------------------
    prep_path = os.path.join(run_dir, "preprocessor.joblib")
    if bool(CFG["reuse_preprocessor_if_present"]) and os.path.exists(prep_path):
        prep = helper.safe_joblib_load(prep_path)
    else:
        prep = helper.fit_preprocessor(dataset_dir, run_dir)

    # -------------------------------------------------------------------------
    # 2) Load train / val / test frames
    # -------------------------------------------------------------------------
    usecols = prep.num_cols + prep.cat_cols + [y1_col, y2_col]
    train_df = collect_split_frame(dataset_dir, "train", usecols, max_train_rows, seed=seed)
    val_df = collect_split_frame(dataset_dir, "val", usecols, max_val_rows, seed=seed + 1)
    test_df = collect_split_frame(dataset_dir, "test", usecols, max_test_rows, seed=seed + 2)

    if train_df.empty or val_df.empty or test_df.empty:
        raise RuntimeError("At least one split is empty after loading. Check processed_dir and max_*_rows settings.")

    # -------------------------------------------------------------------------
    # 3) Stage 1 training set and weights
    # -------------------------------------------------------------------------
    s1_train_df = train_df.copy()
    if bool(combo["apply_loao_stage1"]):
        m_drop = (s1_train_df[y1_col].astype(int) == 1) & (s1_train_df[y2_col].astype(str) == holdout_family)
        s1_train_df = s1_train_df.loc[~m_drop].reset_index(drop=True)

    X1_train = prep.transform(s1_train_df.drop(columns=[y1_col, y2_col], errors="ignore"))
    y1_train = s1_train_df[y1_col].astype(int).to_numpy()
    y2_train = s1_train_df[y2_col].astype(str).fillna("").to_numpy(dtype=object)

    stage1_model = build_stage1_model(
        str(combo["model_family"]),
        dict(combo["stage1_params"]),
        str(combo["stage1_weight_mode"]),
        seed=seed,
    )
    s1_sample_weight = make_stage1_sample_weights(y1_train, y2_train, str(combo["stage1_weight_mode"]), float(CFG["inv_family_clip_max"]))
    if s1_sample_weight is not None:
        stage1_model.fit(X1_train, y1_train, sample_weight=s1_sample_weight)
    else:
        stage1_model.fit(X1_train, y1_train)

    # Validation probabilities for threshold search.
    X_val = prep.transform(val_df.drop(columns=[y1_col, y2_col], errors="ignore"))
    y1_val = val_df[y1_col].astype(int).to_numpy()
    y2_val = val_df[y2_col].astype(str).fillna("").to_numpy(dtype=object)
    p_attack_val = predict_binary_proba(stage1_model, X_val)
    stage1_auc_val = float(roc_auc_score(y1_val, p_attack_val)) if np.unique(y1_val).size >= 2 else float("nan")

    thr_high, thr_best, thr_df = select_stage1_threshold(helper, y1_val, y2_val, p_attack_val)
    thr_df.to_csv(os.path.join(run_dir, "stage1_threshold_grid.csv"), index=False)
    write_json(os.path.join(run_dir, "stage1_threshold_best.json"), thr_best)

    # -------------------------------------------------------------------------
    # 4) Stage 2 training set
    # -------------------------------------------------------------------------
    attack_train_df = train_df.loc[train_df[y1_col].astype(int) == 1].copy()
    attack_train_df = attack_train_df.loc[attack_train_df[y2_col].astype(str).isin(valid_known_families)].reset_index(drop=True)

    if attack_train_df.empty:
        raise RuntimeError("Stage-2 training set is empty after applying valid_known_families.")

    y2_train_labels = attack_train_df[y2_col].astype(str).to_numpy(dtype=object)
    train_family_set = {str(f) for f in y2_train_labels}
    trained_known_families = [fam for fam in valid_known_families if fam in train_family_set]
    missing_train_families = [fam for fam in valid_known_families if fam not in train_family_set]
    if len(trained_known_families) < 2:
        raise RuntimeError(
            "Stage-2 training set has fewer than two known families after row capping: "
            f"{trained_known_families}. Increase max_train_rows or choose another manifest."
        )
    if missing_train_families:
        progress_print(
            "[WARN] Stage-2 row cap dropped known families; evaluating with trained subset: "
            + ", ".join(missing_train_families)
        )
        attack_train_df = attack_train_df.loc[attack_train_df[y2_col].astype(str).isin(trained_known_families)].reset_index(drop=True)
        y2_train_labels = attack_train_df[y2_col].astype(str).to_numpy(dtype=object)

    fam_to_idx = {fam: i for i, fam in enumerate(trained_known_families)}
    y2_train_idx = np.array([fam_to_idx[f] for f in y2_train_labels], dtype=int)
    X2_train = prep.transform(attack_train_df.drop(columns=[y1_col, y2_col], errors="ignore"))
    stage2_weight_mode = str(combo.get("stage2_weight_mode", "balanced"))
    s2_weights = stage2_sample_weights(y2_train_idx, len(trained_known_families), stage2_weight_mode)

    stage2_model = build_stage2_model(
        str(combo["model_family"]),
        dict(combo["stage2_params"]),
        n_classes=len(trained_known_families),
        seed=seed + 10,
    )
    if s2_weights is not None:
        stage2_model.fit(X2_train, y2_train_idx, sample_weight=s2_weights)
    else:
        stage2_model.fit(X2_train, y2_train_idx)

    # Stage-2 validation metrics on known families only.
    attack_val_known_df = val_df.loc[
        (val_df[y1_col].astype(int) == 1) & (val_df[y2_col].astype(str).isin(trained_known_families))
    ].copy()
    if len(attack_val_known_df) > 0:
        X2_val_known = prep.transform(attack_val_known_df.drop(columns=[y1_col, y2_col], errors="ignore"))
        y2_val_known_idx = np.array([fam_to_idx[f] for f in attack_val_known_df[y2_col].astype(str).tolist()], dtype=int)
        p2_val_known = predict_multi_proba(stage2_model, X2_val_known)
        pred2_val_known = np.argmax(p2_val_known, axis=1)
        stage2_macro_f1_val = float(f1_score(y2_val_known_idx, pred2_val_known, average="macro", labels=list(range(len(trained_known_families))), zero_division=0))
    else:
        stage2_macro_f1_val = float("nan")

    # -------------------------------------------------------------------------
    # 5) Tau search on validation
    # -------------------------------------------------------------------------
    p2_val_all = predict_multi_proba(stage2_model, X_val)
    fam_pred_val = np.argmax(p2_val_all, axis=1)
    fam_pmax_val = np.max(p2_val_all, axis=1)
    y_true_sys_val = system_labels_from_truth(y1_val, y2_val, holdout_family, trained_known_families, benign_label, unknown_label)

    tau, tau_best, tau_df = tune_tau(
        helper,
        y_true_sys_val,
        p_attack_val,
        fam_pred_val,
        fam_pmax_val,
        trained_known_families,
        thr_high,
        optimize_tau_for_unknown,
        benign_label,
        unknown_label,
    )
    tau_df.to_csv(os.path.join(run_dir, "tau_grid.csv"), index=False)
    write_json(os.path.join(run_dir, "tau_best.json"), tau_best)

    # -------------------------------------------------------------------------
    # 6) Final test evaluation
    # -------------------------------------------------------------------------
    X_test = prep.transform(test_df.drop(columns=[y1_col, y2_col], errors="ignore"))
    y1_test = test_df[y1_col].astype(int).to_numpy()
    y2_test = test_df[y2_col].astype(str).fillna("").to_numpy(dtype=object)

    p_attack_test = predict_binary_proba(stage1_model, X_test)
    p2_test_all = predict_multi_proba(stage2_model, X_test)
    fam_pred_test = np.argmax(p2_test_all, axis=1)
    fam_pmax_test = np.max(p2_test_all, axis=1)
    y_true_sys_test = system_labels_from_truth(y1_test, y2_test, holdout_family, trained_known_families, benign_label, unknown_label)

    pred_raw_test = helper.system_predict_raw(
        p_attack_test,
        fam_pred_test,
        fam_pmax_test,
        trained_known_families,
        float(thr_high),
        float(tau),
        str(unknown_label),
    )
    pred_sys_test, reject_test = helper.apply_abstain_policy(pred_raw_test, str(unknown_label), policy="abstain")
    test_metrics = compute_system_metrics(y_true_sys_test, pred_sys_test, reject_test, trained_known_families, benign_label, unknown_label)

    pd.DataFrame(
        confusion_matrix(y_true_sys_test, pred_sys_test, labels=[benign_label] + trained_known_families + [unknown_label]),
        index=[benign_label] + trained_known_families + [unknown_label],
        columns=[benign_label] + trained_known_families + [unknown_label],
    ).to_csv(os.path.join(run_dir, "confusion_matrix_system_test.csv"))

    summary = {
        "dataset": dataset,
        "holdout_family": holdout_family,
        "scenario_valid": bool(manifest.get("scenario_valid", True)),
        "model_family": str(combo["model_family"]),
        "model_profile": str(combo.get("model_profile", combo["model_family"])),
        "apply_loao_stage1": bool(combo["apply_loao_stage1"]),
        "stage1_weight_mode": str(combo["stage1_weight_mode"]),
        "stage2_weight_mode": stage2_weight_mode,
        "n_valid_known_families": int(len(trained_known_families)),
        "known_families": "|".join(trained_known_families),
        "n_manifest_known_families": int(len(manifest_known_families)),
        "manifest_known_families": "|".join(manifest_known_families),
        "stage2_missing_train_families": "|".join(missing_train_families),
        "stage1_auc_val": stage1_auc_val,
        "stage2_macro_f1_val": stage2_macro_f1_val,
        "stage1_thr_high": float(thr_high),
        "tau": float(tau),
        "stage1_params": json.dumps(combo["stage1_params"], sort_keys=True),
        "stage2_params": json.dumps(combo["stage2_params"], sort_keys=True),
        **test_metrics,
    }
    write_json(os.path.join(run_dir, "summary.json"), summary)
    return summary


