def make_stage1_sample_weights(y1: np.ndarray, y2_family: np.ndarray, weight_mode: str, clip_max: float) -> Optional[np.ndarray]:
    """
    Build sample weights for Stage 1.

    Supported modes:
      - none
      - inv_family
      - inv_family_clipped

    Notes:
      - Only attack rows are reweighted here. Benign rows keep weight 1.0.
      - class_weight_balanced is handled at model-construction time for RF and therefore
        returns None from this function.
    """
    if weight_mode in {"none", "class_weight_balanced"}:
        return None

    w = np.ones(len(y1), dtype=np.float64)
    attack_mask = (y1 == 1)
    fam = np.array([str(x) for x in y2_family], dtype=object)
    fam_attack = fam[attack_mask]
    fam_attack = np.array([f if (f and f.lower() != "nan") else "UNKNOWN" for f in fam_attack], dtype=object)

    if fam_attack.size == 0:
        return None

    uniq, cnt = np.unique(fam_attack, return_counts=True)
    inv = {u: 1.0 / float(c) for u, c in zip(uniq, cnt)}
    w_attack = np.array([inv[f] for f in fam_attack], dtype=np.float64)
    if weight_mode == "inv_family_clipped":
        w_attack = np.minimum(w_attack, float(clip_max))
    w_attack = w_attack / (np.mean(w_attack) + 1e-12)
    w[attack_mask] = w_attack
    return w


def compute_stage2_sample_weights(y_idx: np.ndarray, n_classes: int) -> np.ndarray:
    """Inverse-frequency class weights for Stage 2 multiclass training."""
    counts = np.bincount(y_idx, minlength=n_classes).astype(np.float64)
    counts = np.maximum(counts, 1.0)
    w = counts.sum() / counts
    w = w / np.mean(w)
    return w[y_idx]


def stage2_sample_weights(y_idx: np.ndarray, n_classes: int, weight_mode: str) -> Optional[np.ndarray]:
    mode = str(weight_mode or "balanced")
    if mode == "none":
        return None
    if mode == "balanced":
        return compute_stage2_sample_weights(y_idx, n_classes)
    raise ValueError(f"Unsupported stage2_weight_mode: {weight_mode}")


def build_stage1_model(model_family: str, params: Dict[str, object], weight_mode: str, seed: int):
    if model_family == "xgb":
        if XGBClassifier is None:
            raise RuntimeError("xgboost is not installed but model_family='xgb' was requested.")
        p = dict(CFG["xgb_binary_defaults"])
        p.update(params)
        p["random_state"] = int(seed)
        p = {k: v for k, v in p.items() if v is not None}
        return XGBClassifier(**p)

    if model_family == "rf":
        p = dict(params)
        p.setdefault("n_jobs", int(CFG.get("n_jobs", 8)))
        p["random_state"] = int(seed)
        if weight_mode == "class_weight_balanced":
            p["class_weight"] = "balanced_subsample"
        return RandomForestClassifier(**p)

    raise ValueError(f"Unsupported model_family for stage1: {model_family}")


def build_stage2_model(model_family: str, params: Dict[str, object], n_classes: int, seed: int):
    if model_family == "xgb":
        if XGBClassifier is None:
            raise RuntimeError("xgboost is not installed but model_family='xgb' was requested.")
        p = dict(CFG["xgb_multi_defaults"])
        p.update(params)
        p["num_class"] = int(n_classes)
        p["random_state"] = int(seed)
        p = {k: v for k, v in p.items() if v is not None}
        return XGBClassifier(**p)

    if model_family == "rf":
        p = dict(params)
        p.setdefault("n_jobs", int(CFG.get("n_jobs", 8)))
        p["random_state"] = int(seed)
        return RandomForestClassifier(**p)

    raise ValueError(f"Unsupported model_family for stage2: {model_family}")


def predict_binary_proba(model, X) -> np.ndarray:
    p = model.predict_proba(X)
    if p.ndim != 2 or p.shape[1] < 2:
        raise RuntimeError("Binary model returned an unexpected probability shape.")
    return p[:, 1].astype(np.float64)


def predict_multi_proba(model, X) -> np.ndarray:
    p = model.predict_proba(X).astype(np.float64)
    p = np.clip(p, 1e-12, 1.0)
    return p / p.sum(axis=1, keepdims=True)


